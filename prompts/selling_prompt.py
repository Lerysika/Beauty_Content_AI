def get_selling_prompt(goal: str | None = None, post_length: str = "medium") -> str:
    """Промпт для продающего поста.

    goal — необязательная конкретная цель поста (например, "заполнить окошки
    на август"). Сейчас нигде не передаётся, зарезервировано на будущее.

    post_length — режим длины (short, medium, long).
    """
    if post_length == "short":
        prompt = """ТИП КОНТЕНТА:
Продающий пост (короткий формат).

Главная задача —
мягко привести подписчика к записи.

Это НЕ рекламный текст.

Это НЕ коммерческое предложение.

СТРУКТУРА ДЛЯ SHORT:

Одна продающая мысль → короткое раскрытие → при необходимости CTA.

НЕ использовать полноценную схему:
Hook → Problem → Emotion → Solution → CTA.

Использовать:
• одну продающую мысль
• короткое раскрытие (2-3 предложения)
• при необходимости CTA (максимум одно короткое предложение)

ВАЖНО ПО ДЛИНЕ:
Целевая длина: 300–450 символов.
НЕ пиши слишком короткие тексты (менее 280 символов).
Если текст получается короче — добавь деталь или расширь мысль.

Пример:
 "Свободные окошки на завтра. Запишись, пока есть. Утренние окошки самые удобные — успеешь до работы."

Запрещено:
• длинные структуры
• несколько аргументов
• подробное описание проблемы
• длинный CTA

"""
    else:
        prompt = """ТИП КОНТЕНТА:
Продающий пост.

Главная задача —
мягко привести подписчика к записи.

Это НЕ рекламный текст.

Это НЕ коммерческое предложение.

Пост должен выглядеть как обычная публикация мастера.

Структура:

1.
Первые две строки должны цеплять внимание.

Используй:

• вопрос;
• жизненную ситуацию;
• неожиданное наблюдение;
• распространенную ошибку клиента.

2.
Покажи проблему клиента.

Не выдумывай проблему.

Используй реальные страхи:

• покрытие быстро отслаивается;
• страшно менять мастера;
• жалко потратить деньги впустую;
• нет времени;
• не знаю, какая процедура подойдет.

3.
Покажи эмоцию.

Человек должен узнать себя.

4.
Незаметно покажи, как услуга помогает решить проблему.

Не продавай в лоб.

5.
Заканчивай естественным CTA.

Например:

"Если давно хотели попробовать — буду рада видеть ❤️"

Запрещено использовать:

• "Успей записаться"

• "Количество мест ограничено"

• "Только сегодня"

• "Самые выгодные цены"

• "Не упустите шанс"

После прочтения человек должен подумать:

"Мне тоже это нужно."

Не пытайся продать услугу напрямую.

Сначала помоги читателю узнать себя.

Только после этого плавно покажи решение.

После прочтения человек должен подумать:

"Мне тоже это нужно."

а не

"Мне что-то продают."

"""

    if goal:
        prompt += f"\nЦЕЛЬ ЭТОГО ПОСТА: {goal}\n"

    return prompt + "\n"
