def get_post_length_prompt(length: str = "medium") -> str:
    """
    Возвращает инструкции по длине поста в зависимости от выбранного режима.

    Args:
        length: Режим длины (short, medium, long)

    Returns:
        Инструкции для модели по длине поста
    """
    if length == "short":
        from prompts.short_post_prompt import get_random_short_format, get_short_post_prompt
        short_format = get_random_short_format()
        return get_short_post_prompt(short_format)

    elif length == "long":
        return """ТРЕБОВАНИЯ К ДЛИНЕ ПОСТА — РАЗВЕРНУТЫЙ РЕЖИМ

Напиши развернутый пост.

Диапазон длины: примерно 850–1100 символов.

Максимум 7–8 абзацев.

Максимальное время чтения: около 1–2 минут.

ВАЖНОЕ ПРАВИЛО:

Развернутый пост — это НЕ статья.

Это полноценная история, рассказанная без лишних деталей.

Разрешается:
• полноценная история;
• кейсы;
• несколько аргументов;
• более глубокое раскрытие темы.

ОГРАНИЧЕНИЕ ИСТОРИИ:

После достижения основной мысли истории модель должна закончить публикацию.

Запрещается:
• продолжать рассказ после кульминации;
• добавлять вторую историю;
• повторять уже понятную мысль другими словами.

После кульминации запрещается:
• повторно объяснять мораль;
• повторять главный вывод;
• еще раз убеждать читателя;
• еще раз усиливать эмоцию.

Если читатель уже понял мысль — история должна закончиться.

ПРАВИЛО "УДАЛЕНИЕ ХВОСТА":

После генерации публикации проверь текст:

Вопрос 1: Можно ли удалить последний абзац без потери смысла?
Если да — удали.

Вопрос 2: Можно ли удалить последние два предложения?
Если смысл сохранится — удали.

Вопрос 3: Закончилась ли история раньше?
Если да — не продолжай писать.

ПРОВЕРКА ПЛОТНОСТИ ТЕКСТА:

Проверь: нет ли ощущения, что текст начинает "растягиваться".

Если:
• мысль уже раскрыта;
• история закончилась;
• вывод понятен;

необходимо завершить публикацию.

Запрещается увеличивать объем ради соответствия максимальному лимиту символов.

НЕ СТРЕМИТЬСЯ К ВЕРХНЕЙ ГРАНИЦЕ:

Если мысль полностью раскрыта раньше — закончи пост, даже если не достигнут верхний предел символов.

Длина является ориентиром, а не жестким лимитом.

"""

    else:  # medium (default)
        return """ТРЕБОВАНИЯ К ДЛИНЕ ПОСТА — СТАНДАРТНЫЙ РЕЖИМ

Напиши пост стандартной длины.

Это основной режим генерации. Он должен использоваться чаще всего.

Диапазон длины: примерно 600–850 символов.

Максимум 5–6 абзацев.

Максимальное время чтения: 40–60 секунд.

Одна раскрытая тема.

Один пример или небольшая история.

Краткий вывод.

Сохраняй хороший темп чтения.

НЕ СТРЕМИТЬСЯ К ВЕРХНЕЙ ГРАНИЦЕ:

Если мысль полностью раскрыта раньше — закончи пост, даже если не достигнут верхний предел символов.

Запрещается:
• дописывать воду;
• повторять уже сказанное;
• делать длинный вывод только ради увеличения объема;
• искусственно увеличивать количество абзацев.

ПРОВЕРКА ПЛОТНОСТИ ТЕКСТА:

Проверь: нет ли ощущения, что текст начинает "растягиваться".

Если:
• мысль уже раскрыта;
• история закончилась;
• вывод понятен;

необходимо завершить публикацию.

Запрещается увеличивать объем ради соответствия максимальному лимиту символов.

Длина является ориентиром, а не жестким лимитом.

"""
