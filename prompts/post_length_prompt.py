def get_post_length_prompt(length: str = "medium") -> str:
    """
    Возвращает инструкции по длине поста в зависимости от выбранного режима.

    Args:
        length: Режим длины (short, medium, long)

    Returns:
        Инструкции для модели по длине поста
    """
    if length == "short":
        return """ТРЕБОВАНИЯ К ДЛИНЕ ПОСТА — КОРОТКИЙ РЕЖИМ

Короткий пост — это самостоятельный формат публикации.

Это НЕ сокращенная версия длинного текста.

Напиши пост специально как короткий текст.

Диапазон длины: примерно 400–600 символов.

Максимум 4–5 небольших абзацев.

ПРИНЦИПЫ НАПИСАНИЯ:

1. Используй только одну мысль

Не пытайся раскрыть несколько идей.

Весь пост должен отвечать только на один вопрос.

2. Минимум объяснений

Не используй длинные рассуждения.

Не повторяй одну мысль разными словами.

Не пиши дополнительные пояснения ради объема.

3. Минимум историй

История допускается только если без нее невозможно раскрыть мысль.

Если история используется — она должна состоять максимум из двух-трех предложений.

4. Один пример

Не используй несколько примеров подряд.

Не делай несколько сравнений.

5. Быстрый темп чтения

Текст должен читаться примерно за 20–30 секунд.

У пользователя должно возникать ощущение легкого, быстрого поста.

6. Не делай длинный вывод

Если мысль закончилась — нужно закончить публикацию.

Не добавляй дополнительную мораль.

Не пиши вывод только потому, что "так принято".

7. Не увеличивай объем искусственно

Запрещается:
• повторять мысль;
• делать длинные вступления;
• добавлять лишние детали;
• использовать воду.

Если мысль полностью раскрыта раньше — закончи пост.

Длина является ориентиром, а не жестким лимитом.

"""

    elif length == "long":
        return """ТРЕБОВАНИЯ К ДЛИНЕ ПОСТА — РАЗВЕРНУТЫЙ РЕЖИМ

Напиши развернутый пост.

Диапазон длины: примерно 1000–1400 символов.

Максимум 9–10 абзацев.

Разрешается:
• полноценная история;
• кейсы;
• несколько аргументов;
• более глубокое раскрытие темы.

Не превращай текст в статью.

Если мысль полностью раскрыта раньше — закончи пост.

Запрещается:
• дописывать воду;
• повторять уже сказанное;
• делать длинный вывод только ради увеличения объема;
• искусственно увеличивать количество абзацев.

Длина является ориентиром, а не жестким лимитом.

"""

    else:  # medium (default)
        return """ТРЕБОВАНИЯ К ДЛИНЕ ПОСТА — СТАНДАРТНЫЙ РЕЖИМ

Напиши пост стандартной длины.

Диапазон длины: примерно 700–1000 символов.

Максимум 6–7 абзацев.

Одна раскрытая тема.

Один пример или небольшая история.

Краткий вывод.

Сохраняй хороший темп чтения.

Если мысль полностью раскрыта раньше — закончи пост.

Запрещается:
• дописывать воду;
• повторять уже сказанное;
• делать длинный вывод только ради увеличения объема;
• искусственно увеличивать количество абзацев.

Длина является ориентиром, а не жестким лимитом.

"""
