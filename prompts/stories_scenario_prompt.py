"""Промпты для генерации сценария Stories."""


def get_stories_scenario_prompt(
    goal: str,
    idea: dict,
    profile: dict | None = None,
) -> str:
    """
    Возвращает промпт для генерации сценария Stories на основе выбранной идеи.

    Args:
        goal: Цель Stories (sell, engage, about_me, expertise, work, behind_scenes, unknown)
        idea: Выбранная идея с полями title и description
        profile: Профиль пользователя

    Returns:
        Строка с промптом для AI
    """
    idea_title = idea.get("title", "")
    idea_description = idea.get("description", "")

    goal_descriptions = {
        "sell": "Продажа услуги",
        "engage": "Вовлечение аудитории",
        "about_me": "Показать себя",
        "expertise": "Показать экспертность",
        "work": "Показать работу",
        "behind_scenes": "Показать закулисье",
        "unknown": "Разнообразный контент",
    }

    goal_text = goal_descriptions.get(goal, "Stories")

    return f"""Ты — эксперт по контенту для бьюти-мастеров в Instagram Stories.

Твоя задача: создать готовый сценарий из 4–7 Stories на основе выбранной идеи.

ЦЕЛЬ СТОРИС: {goal_text}

ВЫБРАННАЯ ИДЕЯ:
Название: {idea_title}
Описание: {idea_description}

ТРЕБОВАНИЯ К СЦЕНАРИЮ:

1. Количество Stories: 4–7 экранов (оптимально 5–6).

2. Каждый экран должен содержать:
   - format: формат (Видео, Фото, Коллаж, Talking head)
   - what_to_show: конкретное действие, что показать
   - text: короткий текст на экран (разговорный стиль, без длинных абзацев, без AI-клише)
   - interaction: интерактив (poll, question, slider) — только если уместно, иначе null

3. Формат должен быть реалистичным:
   - Видео: для процессов, движений, демонстраций
   - Фото: для результатов, до/после, деталей
   - Коллаж: для сравнений, подборок
   - Talking head: для объяснений, личных историй

4. what_to_show должно быть КОНКРЕТНЫМ:
   ❌ "Покажи экспертность"
   ✅ "Сними крупный план процесса нанесения покрытия"

5. Текст должен быть:
   - разговорным, как будто говоришь с подругой
   - короткими фразами
   - без сложных слов
   - без AI-клише ("в современном мире", "важно отметить")

6. Интерактив добавляй только если он действительно улучшает Stories:
   - poll: для опросов, выбора
   - question: для вопросов аудитории
   - slider: для оценок, мнений
   Не добавляй интерактив автоматически к каждому экрану.

СТРОГИЕ ЗАПРЕТЫ:

❌ НЕ придумывай:
- клиентов и их истории
- отзывы
- кейсы с результатами
- конкретные цены
- акции и скидки
- свободные места
- гарантии
- результаты процедур (если не указано в профиле)
- оборудование которого нет в профиле
- услуги которых нет в профиле

❌ НЕ используй:
- выдуманные факты о пользователе
- выдуманные кейсы как реальные
- прямолинейную рекламу (если цель не продажа)

✅ ИСПОЛЬЗУЙ ТОЛЬКО:
- услуги из профиля пользователя
- специализацию из профиля
- реалистичные сценарии

ФОРМАТ ОТВЕТА:

Верни строго JSON-объект:
{{
  "title": "Название сценария",
  "stories": [
    {{
      "number": 1,
      "format": "Видео",
      "what_to_show": "Что конкретно показать",
      "text": "Текст на экран",
      "interaction": null
    }}
  ]
}}

Никаких Markdown-блоков, никаких комментариев вне JSON."""
