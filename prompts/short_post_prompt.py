import random

# Список микроформатов для коротких постов
SHORT_POST_FORMATS = [
    "qa",
    "observation",
    "dialog",
    "fact",
    "situation",
    "opinion",
    "emotion",
    "unexpected_question"
]

def get_random_short_format() -> str:
    """
    Возвращает случайный микроформат для короткого поста.

    Returns:
        Случайный формат из списка SHORT_POST_FORMATS
    """
    return random.choice(SHORT_POST_FORMATS)


def get_short_post_prompt(format: str) -> str:
    """
    Возвращает инструкции для генерации короткого поста в зависимости от выбранного микроформата.

    Args:
        format: Микроформат (myth, advice, observation, qa, fact, mini_story, opinion, question)

    Returns:
        Инструкции для модели по генерации короткого поста
    """
    base_instruction = """МИНИ-ПУБЛИКАЦИЯ — ОТДЕЛЬНЫЙ ЖАНР

Мини-публикация — это НЕ сокращенная версия стандартного поста.

Это быстрый пост между клиентами.

Напиши мини-публикацию СРАЗУ как мини-публикацию.

НЕ пиши сначала полноценный пост, а потом сокращай его.

Диапазон длины: примерно 300–500 символов.

Максимум 3–4 небольших абзацев.

Максимум 8 предложений.

Максимальное время чтения: 15–20 секунд.

ГЛАВНЫЙ ОРИЕНТИР:

Представь ситуацию: мастер только что закончил работу. До следующего клиента осталось две минуты. Она быстро открывает Telegram, пишет публикацию, отправляет её, возвращается к работе.

Именно так должна ощущаться каждая мини-публикация.

ОСНОВНОЙ ПРИНЦИП:

Каждая мини-публикация должна содержать ТОЛЬКО ОДНУ МЫСЛЬ.

После того как мысль закончилась — публикация должна закончиться тоже.

Запрещается искусственно продолжать текст.

"""

    format_instructions = {
        "qa": """ФОРМАТ: ВОПРОС КЛИЕНТА — ОТВЕТ МАСТЕРА

Структура:
1. Один вопрос клиента
2. Один ответ мастера
3. Конец

Пример:
"Можно ли делать маникюр, если на коже есть царапина?"
Нет, это может привести к инфекции. Подожди, пока кожа заживет.

ОГРАНИЧЕНИЯ:
• Не используй несколько вопросов
• Не делай длинное вступление
• Ответ должен быть кратким

""",

        "observation": """ФОРМАТ: ОДНО НАБЛЮДЕНИЕ

Структура:
1. Одно наблюдение
2. Одна мысль
3. Конец

Пример:
Клиенты с ухоженными руками чаще возвращаются.
Забота о себе — это отношение к себе.

ОГРАНИЧЕНИЯ:
• Не делай длинную драматургию
• Не описывай несколько наблюдений
• Закончи после одной мысли

""",

        "dialog": """ФОРМАТ: МИНИ-ДИАЛОГ

Структура:
1. Мини-диалог
2. Одна реплика
3. Конец

Пример:
"А можно сделать короче?"
Конечно, короче смотрится аккуратнее.

ОГРАНИЧЕНИЯ:
• Не делай длинный диалог
• Не добавляй несколько реплик
• Закончи после одной реплики

""",

        "fact": """ФОРМАТ: ОДИН ИНТЕРЕСНЫЙ ФАКТ

Структура:
1. Один интересный факт
2. Небольшой комментарий
3. Конец

Пример:
Ногти растут быстрее летом.
Кровообращение улучшается в теплую погоду.

ОГРАНИЧЕНИЯ:
• Не используй несколько фактов
• Не добавляй длинные объяснения
• Не превращай в мини-статью

""",

        "situation": """ФОРМАТ: ОДНА СИТУАЦИЯ

Структура:
1. Одна ситуация
2. Короткая реакция мастера
3. Конец

Пример:
Вчера клиентка пришла с обломанным ногтем.
Успела быстро восстановить форму.

ОГРАНИЧЕНИЯ:
• Не делай длинную историю
• Не добавляй дополнительные детали
• Закончи после короткой реакции

""",

        "opinion": """ФОРМАТ: ОДНО ЛИЧНОЕ МНЕНИЕ

Структура:
1. Одно личное мнение
2. Без объяснения на несколько абзацев

Пример:
Честно говоря, не верю в чудо-средства.
Здоровье волос — это комплексный уход.

ОГРАНИЧЕНИЯ:
• Не делай длинное вступление
• Не используй несколько мнений
• Не объясняй на несколько абзацев

""",

        "emotion": """ФОРМАТ: ОДНА ЭМОЦИЯ

Структура:
1. Одна эмоция
2. Одна мысль
3. Конец

Пример:
Так приятно видеть довольных клиентов.
Именно ради этого я работаю.

ОГРАНИЧЕНИЯ:
• Не усиливай эмоцию
• Не добавляй длинные объяснения
• Закончи после одной мысли

""",

        "unexpected_question": """ФОРМАТ: ОДИН НЕОЖИДАННЫЙ ВОПРОС

Структура:
1. Один неожиданный вопрос
2. Короткий ответ
3. Конец

Пример:
А вы знали, что ногти растут быстрее ночью?
Да, это связано с циркадными ритмами.

ОГРАНИЧЕНИЯ:
• Не делай длинное рассуждение
• Не превращай в полноценную статью
• Закончи после короткого ответа

"""
    }

    prompt = base_instruction + format_instructions.get(format, format_instructions["qa"])

    # Общие ограничения для всех форматов
    common_restrictions = """ОБЩИЕ ОГРАНИЧЕНИЯ ДЛЯ МИНИ-ПУБЛИКАЦИЙ:

ЗАПРЕЩЕНА ПОЛНОЦЕННАЯ СТРУКТУРА ПОСТА:

Нельзя автоматически строить публикацию по схеме:
Проблема → Объяснение → История → Вывод → CTA

Именно эта структура делает мини-публикацию похожей на обычный пост.

ОГРАНИЧЕНИЕ СМЫСЛОВЫХ БЛОКОВ:

Максимум: 2–3 смысловых блока.
Не больше.
Если появляется четвертый блок — необходимо закончить публикацию.

ОГРАНИЧЕНИЕ ПРЕДЛОЖЕНИЙ:

Максимум: 8 предложений.
После восьмого предложения публикация должна завершиться.
Даже если тема не полностью раскрыта.

ЗАПРЕЩЕНЫ ДЛИННЫЕ ИСТОРИИ:

В режиме Mini запрещается писать полноценные истории клиентов.
Если используется история — она должна занимать максимум 2–3 предложения.
После этого история заканчивается без дополнительных подробностей.

ЗАПРЕЩЕНО РАЗВИТИЕ СЮЖЕТА:

Если история уже донесла мысль — нельзя:
• добавлять новые события
• добавлять новые диалоги
• продолжать рассказ
• усиливать эмоции
• объяснять мораль

История должна закончиться сразу после основной идеи.

ЗАПРЕЩЕНЫ СПИСКИ:

Полностью запретить:
• нумерацию
• списки
• несколько советов
• несколько причин
• несколько рекомендаций

Если модель хочет написать список — значит она нарушила требования режима Mini.

ЗАПРЕЩЕНЫ МИНИ-СТАТЬИ:

Запрещается:
• подробно объяснять тему
• раскрывать несколько аспектов
• делать экспертный разбор
• использовать конструкции: "Во-первых", "Во-вторых", "Вот почему", "Поэтому", "Именно поэтому", "Давайте разберемся", "Например" в качестве начала нового смыслового блока

УПРОСТИТЬ ЯЗЫК:

Публикация должна ощущаться как живая речь мастера.
Разрешается:
• короткие предложения
• разговорные формулировки
• незавершенные мысли
• легкие эмоциональные комментарии

Не стремиться сделать текст литературным.

НЕ СТРЕМИТЬСЯ ЗАКОНЧИТЬ КРАСИВО:

Мини-публикация НЕ обязана иметь:
• красивый финал
• мораль
• эмоциональную кульминацию
• продающее завершение

Иногда публикация может закончиться:
• вопросом
• наблюдением
• одной фразой
• короткой эмоцией
• репликой клиента

Это считается нормальным.

НОВЫЙ ПРИНЦИП ПРОВЕРКИ:

После генерации проверь текст. Ответь на вопросы:

Вопрос 1: Похоже ли это на уменьшенную копию стандартного поста?
Если да — полностью перепиши.

Вопрос 2: Можно ли удалить половину текста без потери основной мысли?
Если да — удали.

Вопрос 3: Можно ли закончить публикацию раньше?
Если да — закончи раньше.

Вопрос 4: Появилась ли полноценная история?
Если да — сократи её до нескольких предложений.

Вопрос 5: Не начал ли текст превращаться в статью?
Если да — полностью перепиши.

Длина является ориентиром, а не жестким лимитом.
"""

    return prompt + common_restrictions
